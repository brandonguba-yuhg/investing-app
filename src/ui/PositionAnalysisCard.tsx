import { useEffect, useState } from "react";
import { ProviderError } from "../core/provider";
import type { InvestorProfile, PortfolioPosition, PositionAnalysis } from "../core/types";
import { useProvider } from "./providerContext";

interface Props {
  symbol: string;
  portfolio: PortfolioPosition[];
  profile: InvestorProfile | null;
  onClose: () => void;
}

const RISK_LABEL: Record<PositionAnalysis["riskLevel"], string> = {
  low: "Low risk",
  moderate: "Moderate risk",
  elevated: "Elevated risk",
  high: "High risk",
};

/**
 * AI assessment of a single position in portfolio context. Shown automatically
 * after a position is added or changed, and on demand from a holding card.
 */
export function PositionAnalysisCard({ symbol, portfolio, profile, onClose }: Props) {
  const provider = useProvider();
  const [analysis, setAnalysis] = useState<PositionAnalysis | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;
    setAnalysis(null);
    setError(null);
    provider
      .getPositionAnalysis(symbol, portfolio, profile)
      .then((a) => {
        if (!cancelled) setAnalysis(a);
      })
      .catch((e: unknown) => {
        if (cancelled) return;
        const status = e instanceof ProviderError ? e.status : undefined;
        if (status === 501 || status === 503) {
          setError("Position analysis needs the backend AI provider.");
        } else {
          setError(e instanceof Error ? e.message : "Analysis failed.");
        }
      });
    return () => {
      cancelled = true;
    };
    // Intentionally keyed on symbol only: the portfolio/profile snapshot at
    // open time is what we analyze; re-running on every quote tick would spam
    // the AI endpoint.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [symbol, provider]);

  return (
    <div className="pos-analysis">
      <div className="pos-head">
        <div className="pos-title">
          <h3>
            {symbol} <span className="pos-title-sub">position check</span>
          </h3>
          {analysis && (
            <span className={`pos-risk pos-risk-${analysis.riskLevel}`}>
              {RISK_LABEL[analysis.riskLevel]}
            </span>
          )}
        </div>
        <button className="pos-close" onClick={onClose} title="Dismiss">
          ✕
        </button>
      </div>

      {!analysis && !error && (
        <div className="loading">Looking at {symbol} inside your portfolio…</div>
      )}
      {error && <div className="pos-error">{error}</div>}

      {analysis && (
        <>
          <p className="pos-summary">{analysis.summary}</p>

          <div className="pos-notes">
            <div className="pos-note">
              <span className="pos-note-label">Fit with your profile</span>
              <p>{analysis.fitNotes}</p>
            </div>
            <div className="pos-note">
              <span className="pos-note-label">Portfolio impact</span>
              <p>{analysis.portfolioImpact}</p>
            </div>
          </div>

          <div className="pos-cases">
            <div className="pos-case">
              <span className="pos-case-label up-text">Bull case</span>
              <ul>
                {analysis.bullCase.map((b, i) => (
                  <li key={i}>{b}</li>
                ))}
              </ul>
            </div>
            <div className="pos-case">
              <span className="pos-case-label down-text">Bear case</span>
              <ul>
                {analysis.bearCase.map((b, i) => (
                  <li key={i}>{b}</li>
                ))}
              </ul>
            </div>
          </div>

          <div className="pos-foot">Generated by Claude. Informational only — not investment advice.</div>
        </>
      )}
    </div>
  );
}
