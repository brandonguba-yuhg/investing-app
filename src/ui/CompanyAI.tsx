import { useEffect, useState } from "react";
import type { AIAnalysis, Ticker } from "../core/types";
import { useProvider } from "./providerContext";

interface Props {
  symbol: Ticker;
}

interface AskEntry {
  question: string;
  answer?: string;
  error?: string;
  loading: boolean;
}

export function CompanyAI({ symbol }: Props) {
  const provider = useProvider();
  const [analysis, setAnalysis] = useState<AIAnalysis | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [unavailable, setUnavailable] = useState(false);

  const [question, setQuestion] = useState("");
  const [asks, setAsks] = useState<AskEntry[]>([]);
  const [asking, setAsking] = useState(false);

  useEffect(() => {
    let cancelled = false;
    setLoading(true);
    setError(null);
    setUnavailable(false);
    setAsks([]);
    provider
      .getAnalysis(symbol)
      .then((a) => {
        if (!cancelled) setAnalysis(a);
      })
      .catch((e) => {
        if (cancelled) return;
        const msg = e instanceof Error ? e.message : "Failed to load";
        // 503 => AI not configured on the backend; hide the section.
        if (/503|not configured/i.test(msg)) setUnavailable(true);
        else setError(msg);
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [symbol, provider]);

  const submitAsk = async () => {
    const q = question.trim();
    if (!q || asking) return;
    setQuestion("");
    const idx = asks.length;
    setAsks((prev) => [...prev, { question: q, loading: true }]);
    setAsking(true);
    try {
      const { answer } = await provider.ask(symbol, q);
      setAsks((prev) =>
        prev.map((a, i) => (i === idx ? { ...a, answer, loading: false } : a)),
      );
    } catch (e) {
      const msg = e instanceof Error ? e.message : "Failed";
      setAsks((prev) =>
        prev.map((a, i) => (i === idx ? { ...a, error: msg, loading: false } : a)),
      );
    } finally {
      setAsking(false);
    }
  };

  if (unavailable) return null; // backend has no AI key — quietly omit

  return (
    <section className="ai-card score-card">
      <div className="score-card-head">
        <h3>AI Analysis</h3>
        <span className="ai-badge">Claude</span>
      </div>

      {loading ? (
        <div className="ai-loading">Analyzing the fundamentals…</div>
      ) : error ? (
        <div className="ai-error">{error}</div>
      ) : analysis ? (
        <>
          <p className="ai-summary">{analysis.summary}</p>

          <div className="ai-cases">
            <div className="ai-case bull">
              <h4>Bull case</h4>
              <ul>
                {analysis.bullCase.map((b, i) => (
                  <li key={i}>{b}</li>
                ))}
              </ul>
            </div>
            <div className="ai-case bear">
              <h4>Bear case</h4>
              <ul>
                {analysis.bearCase.map((b, i) => (
                  <li key={i}>{b}</li>
                ))}
              </ul>
            </div>
          </div>

          <div className="ai-ask">
            <div className="ai-ask-row">
              <input
                type="text"
                value={question}
                onChange={(e) => setQuestion(e.target.value)}
                onKeyDown={(e) => {
                  if (e.key === "Enter") submitAsk();
                }}
                placeholder={`Ask anything about ${symbol}…`}
                maxLength={500}
                disabled={asking}
              />
              <button onClick={submitAsk} disabled={asking || !question.trim()}>
                Ask
              </button>
            </div>

            {asks.map((a, i) => (
              <div className="ai-qa" key={i}>
                <div className="ai-q">{a.question}</div>
                {a.loading ? (
                  <div className="ai-a loading">Thinking…</div>
                ) : a.error ? (
                  <div className="ai-a error">{a.error}</div>
                ) : (
                  <div className="ai-a">{a.answer}</div>
                )}
              </div>
            ))}
          </div>

          <p className="ai-disclaimer">
            Generated by Claude from this company's fundamentals. Informational
            only — not investment advice.
          </p>
        </>
      ) : null}
    </section>
  );
}
